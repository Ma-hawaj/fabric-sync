-- Fresh-database baseline: locations, sales, production, and collection.

-- A physical location. It can be a branch where customers collect finished
-- orders, a store that only holds material stock, or both — so the two
-- capabilities are independent flags rather than a single type column.
-- Deactivating a location hides it from both pickers without touching the
-- stock rows and invoices that still reference it.
CREATE TABLE branch (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    name TEXT NOT NULL UNIQUE,
    receives_orders BOOLEAN NOT NULL DEFAULT TRUE,
    holds_stock BOOLEAN NOT NULL DEFAULT TRUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE customers (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    name TEXT NOT NULL,
    mobile_no TEXT NOT NULL,
    address TEXT,
    whatsapp_notifications_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (name, mobile_no)
);

CREATE TABLE materials (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    name TEXT NOT NULL,
    sku TEXT,
    unit TEXT NOT NULL DEFAULT 'meters',
    -- Fabric family grouping a fabric's colour variants ("Zabrjad 1" and
    -- "Zabrjad 2" are both family "Zabrjad"), so the inventory table can
    -- cluster them behind one filter. NULL on rows that need no grouping.
    family TEXT,
    junior_price NUMERIC(10, 2) CHECK (junior_price >= 0),
    normal_price NUMERIC(10, 2) CHECK (normal_price >= 0),
    large_price NUMERIC(10, 2) CHECK (large_price >= 0),
    CHECK ((junior_price IS NULL AND normal_price IS NULL AND large_price IS NULL)
        OR (junior_price IS NOT NULL AND normal_price IS NOT NULL AND large_price IS NOT NULL))
);

-- A material can be stocked at more than one location (branch), so stock is
-- tracked per material/location pair rather than as a single quantity.
CREATE TABLE material_stock (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    material_id UUID NOT NULL REFERENCES materials(id),
    branch_id UUID NOT NULL REFERENCES branch(id),
    quantity NUMERIC(10, 2) NOT NULL DEFAULT 0,
    UNIQUE (material_id, branch_id)
);

-- An invoice is settled through any number of payments — advances at
-- creation, per-pickup payments as orders are collected, till payments in
-- between — each its own row in invoice_payments below. The invoices table
-- itself stores no money state: what is paid is the ledger's sum, and what
-- the customer still owes is total_price - gift_card_redeemed - that sum.
CREATE TABLE invoices (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    -- A tax invoice has to carry a human-readable number and the moment it was
    -- issued. The uuidv7 primary key is neither: it is not something a customer
    -- can quote back, and a bare DATE would lose the time of day, so the
    -- timestamp in the printed document's QR code would otherwise have to
    -- invent midnight.
    invoice_number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    total_price NUMERIC(10, 2) NOT NULL DEFAULT 0,
    -- Server-set at creation and immutable afterwards: staff never enter this.
    -- What they do promise is target_date below, the editable delivery date.
    invoice_date TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- When the garment is promised for, if at all. Staff-editable, unlike
    -- invoice_date above; blank means no committed pickup.
    target_date DATE,
    -- Computed sum of the individual order charges, kept for invoice totals.
    urgent_charge NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (urgent_charge >= 0),
    collection_method TEXT NOT NULL DEFAULT 'pickup'
        CHECK (collection_method IN ('delivery', 'pickup')),
    branch_id UUID REFERENCES branch(id),
    discount NUMERIC(10, 2) NOT NULL DEFAULT 0,
    discount_unit TEXT NOT NULL DEFAULT 'amount' CHECK (discount_unit IN ('amount', 'percent')),
    -- A tailoring invoice finds its customer through orders → measurements, but
    -- a sale of only products or gift cards has no orders to go through. This
    -- names the buyer directly for those; it stays NULL on ordinary invoices.
    customer_id UUID REFERENCES customers(id),
    -- A gift card is tender rather than a discount, so total_price stays the
    -- gross amount charged and this sits alongside the ledger instead of
    -- reducing the total. It is a settlement channel next to the payments
    -- below, so what the customer actually hands over to clear the invoice is
    -- total_price - gift_card_redeemed.
    gift_card_redeemed NUMERIC(10, 2) NOT NULL DEFAULT 0,
    notification_revision BIGINT NOT NULL DEFAULT 0,
    readiness_generation BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE measurements (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    customer_id UUID NOT NULL REFERENCES customers(id),
    measurement_date DATE NOT NULL DEFAULT CURRENT_DATE,

    -- Three decimal places preserve eighth-inch measurements (⅛ = 0.125),
    -- while keeping the original four digits for the whole-number part.
    front_height NUMERIC(7, 3),
    back_height NUMERIC(7, 3),
    chest NUMERIC(7, 3),
    waist NUMERIC(7, 3),
    hip NUMERIC(7, 3),
    shoulder NUMERIC(7, 3),
    shoulder_down NUMERIC(7, 3),
    sleeve_length NUMERIC(7, 3),
    neck_size NUMERIC(7, 3),
    open_hand NUMERIC(7, 3),
    chest_up NUMERIC(7, 3),
    cuff_width NUMERIC(7, 3),
    cuff_size NUMERIC(7, 3),
    neck_width NUMERIC(7, 3),
    armhole NUMERIC(7, 3),
    fo_width NUMERIC(7, 3),
    fo NUMERIC(7, 3),
    bottom NUMERIC(7, 3),
    bottom_fold NUMERIC(7, 3),
    full_body NUMERIC(7, 3),
    sleeve_half NUMERIC(7, 3),
    open_fold NUMERIC(7, 3),
    front_pocket_length NUMERIC(7, 3),
    front_pocket_length_by_width TEXT,
    side_pocket NUMERIC(7, 3),
    side_pocket_length_by_width TEXT,
    mobile_pocket_length_by_width TEXT,
    -- Record-level choices rather than lengths: what was measured (the
    -- customer's body, an existing thobe, a sample) and how to cut it.
    -- Nullable so rows written before these existed keep reading — every
    -- new write has to set them (see validate_measurement).
    type TEXT CHECK (type IN ('body', 'thobe', 'sample')),
    fit TEXT CHECK (fit IN ('loose', 'fit', 'medium'))
);

CREATE TABLE orders (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    measurement_id UUID NOT NULL REFERENCES measurements(id),
    material_source TEXT NOT NULL DEFAULT 'shop' CHECK (material_source IN ('shop', 'customer')),
    material_id UUID REFERENCES materials(id),
    customer_material_description TEXT,
    material_amount NUMERIC(10, 2) NOT NULL CHECK (material_amount > 0),
    CONSTRAINT orders_material_details_check CHECK (
        (material_source = 'shop' AND material_id IS NOT NULL AND customer_material_description IS NULL)
        OR
        (material_source = 'customer' AND material_id IS NULL
         AND customer_material_description IS NOT NULL
         AND length(btrim(customer_material_description)) > 0)
    ),
    invoice_id UUID NOT NULL REFERENCES invoices(id),
    price NUMERIC(10, 2) NOT NULL,
    base_price NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (base_price >= 0),
    is_urgent BOOLEAN NOT NULL DEFAULT false,
    urgent_charge NUMERIC(10, 2) NOT NULL DEFAULT 0,
    CONSTRAINT orders_urgent_charge_check
        CHECK ((is_urgent AND urgent_charge > 0) OR (NOT is_urgent AND urgent_charge = 0)),
    thobe_type TEXT,
    f_pocket TEXT,
    s_pocket TEXT,
    collar TEXT,
    sleeve TEXT,
    patti TEXT,
    emd TEXT,
    more_details TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'ready', 'collected')),
    collected_at TIMESTAMPTZ,
    ready_at TIMESTAMPTZ,
    ready_by TEXT,
    readiness_version BIGINT NOT NULL DEFAULT 0,
    ready_location_id UUID REFERENCES branch(id),
    -- A garment handed to a tailor needs a number the tailor can quote back,
    -- just like the tax invoice it rides on. The uuidv7 primary key is not
    -- quotable, so the human-readable identity lives here instead.
    order_number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    -- Where the garment is actually made, which is not necessarily where the
    -- customer collects it (that is the invoice's branch_id). NULL until
    -- production is assigned. When the two differ the garment has to be moved
    -- between locations, which is what a `requires_delivery` stage tracks.
    production_branch_id UUID REFERENCES branch(id)
);

-- Every payment against an invoice, in the order it was taken: advances at
-- creation, per-pickup payments as orders are collected, till payments in
-- between. Defined after orders so a payment taken at a pickup can point at
-- it.
CREATE TABLE invoice_payments (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    invoice_id UUID NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
    -- The pickup this payment was taken at, when it was taken at one. NULL
    -- for advances and till payments not tied to a collection.
    order_id UUID REFERENCES orders(id) ON DELETE SET NULL,
    amount NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
    -- Nullable: the app always records a method, but rows imported without a
    -- recorded method (see scripts/ingest_xlsm.py) keep NULL.
    payment_type TEXT CHECK (payment_type IN ('benefit', 'cash', 'card')),
    paid_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- The stages a garment passes through in production. Staff edit this list, so
-- it is a table rather than more values on orders.status — same reasoning as
-- `branch`, and the same retirement rule: is_active instead of a delete, so the
-- progress rows pointing at a retired stage stay readable.
CREATE TABLE order_stages (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    name TEXT NOT NULL UNIQUE,
    sort_order INTEGER NOT NULL,
    -- Marks a stage that only applies when the garment changes location. It is
    -- treated as not applicable on an order produced where the customer
    -- collects, rather than left hanging as an unfinished step.
    requires_delivery BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- A finished order brought back for modification or repair. Each return is its
-- own record with its own status, so an order repaired twice keeps both
-- histories. `charge` is recorded for the books; billing a repair through an
-- invoice is out of scope for now, which is why there is no invoice_id here.
-- A repair is received back by the customer after completion (`received`), at
-- which point an optional payment for the repair work can be recorded on the
-- repair row itself (`received_amount`/`received_payment_type`) — the invoice
-- ledger is untouched. `fixed_measurement_id` points at the new measurement
-- row a repair's measurement fix created (if any), so the fix stays on record
-- for future orders; the order's own `measurement_id` snapshot never moves.
CREATE TABLE order_repairs (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    order_id UUID NOT NULL REFERENCES orders(id),
    reason TEXT NOT NULL,
    reported_on DATE NOT NULL DEFAULT CURRENT_DATE,
    charge NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (charge >= 0),
    status TEXT NOT NULL DEFAULT 'open'
        CHECK (status IN ('open', 'in_progress', 'completed', 'cancelled', 'received')),
    completed_at TIMESTAMPTZ,
    received_at TIMESTAMPTZ,
    received_amount NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (received_amount >= 0),
    received_payment_type TEXT,
    fixed_measurement_id UUID REFERENCES measurements(id) ON DELETE SET NULL,
    notes TEXT
);

-- Records only the stages actually acted on. The checklist itself is derived by
-- overlaying these rows onto the live `order_stages` list, so adding or
-- retiring a stage takes effect on in-flight orders with no backfill, and
-- nothing has to be seeded when an invoice creates an order.
--
-- One checklist per order, covering the original build only — a repair is
-- tracked by its own record and status (see order_repairs above), not by a
-- second pass through these stages.
CREATE TABLE order_stage_progress (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    order_id UUID NOT NULL REFERENCES orders(id),
    stage_id UUID NOT NULL REFERENCES order_stages(id),
    -- 'skipped' is how a stage that doesn't apply to this particular garment is
    -- cleared without pretending it was done. Undoing a stage deletes the row
    -- rather than storing a third 'pending' value.
    status TEXT NOT NULL CHECK (status IN ('done', 'skipped')),
    completed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Where a delivery stage delivered to. NULL on every other stage.
    location_id UUID REFERENCES branch(id),
    notes TEXT,
    UNIQUE (order_id, stage_id)
);

-- Who's responsible for a stage, independent of order_stage_progress: a stage
-- can be assigned before any work happens, so it can't be a column on rows
-- that only exist once a stage is done or skipped. One assignee at a time per
-- order/stage — assigning again overwrites rather than stacking, and there is
-- no repair_id here for the same reason order_stage_progress dropped it: a
-- repair is tracked by its own record, not a second pass through the stages.
--
-- assignee_id is TEXT rather than a foreign key because there is no local
-- user table yet (see features/users) — it is mocked pending real auth and a
-- Zitadel-backed directory. assignee_name is denormalized alongside it so a
-- past assignment still reads sensibly if that directory ever changes.
CREATE TABLE order_stage_assignments (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    order_id UUID NOT NULL REFERENCES orders(id),
    stage_id UUID NOT NULL REFERENCES order_stages(id),
    assignee_id TEXT NOT NULL,
    assignee_name TEXT NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (order_id, stage_id)
);

-- Per-account user settings. One row per user; one nullable column per
-- preference, starting with the default location — future preferences add
-- columns, not tables. user_id is the Zitadel subject as TEXT rather than a
-- foreign key because there is no local user table (same precedent as
-- order_stage_assignments.assignee_id).
CREATE TABLE user_preferences (
    user_id TEXT PRIMARY KEY,
    default_location_id UUID REFERENCES branch(id) ON DELETE SET NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- A finished good sold as-is, as opposed to `materials`, which are raw fabric
-- consumed by a tailoring order. A product carries a list price because it
-- sells at one; an order's price is typed in per line instead. Deactivating a
-- product retires it without disturbing the invoice lines that reference it.
CREATE TABLE products (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    name TEXT NOT NULL,
    sku TEXT UNIQUE,
    unit_price NUMERIC(10, 2) NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- Mirrors material_stock: a product can sit at more than one location.
CREATE TABLE product_stock (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    product_id UUID NOT NULL REFERENCES products(id),
    branch_id UUID NOT NULL REFERENCES branch(id),
    quantity NUMERIC(10, 2) NOT NULL DEFAULT 0,
    UNIQUE (product_id, branch_id)
);

-- Stored value. `balance` is decremented as the card is spent across invoices,
-- so it outlives the sale that created it. The invoice that sold a card is
-- found through invoice_items rather than duplicated here.
CREATE TABLE gift_cards (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    code TEXT NOT NULL UNIQUE,
    initial_amount NUMERIC(10, 2) NOT NULL,
    balance NUMERIC(10, 2) NOT NULL,
    customer_id UUID REFERENCES customers(id),
    expires_on DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- Audit trail of every redemption; gift_cards.balance is the running total the
-- redemptions add up to.
CREATE TABLE gift_card_redemptions (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    gift_card_id UUID NOT NULL REFERENCES gift_cards(id),
    invoice_id UUID NOT NULL REFERENCES invoices(id),
    amount NUMERIC(10, 2) NOT NULL,
    redeemed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- A card can only be applied once per invoice; a repeat surfaces as a 409
    -- through the unique-violation mapping in error.rs.
    UNIQUE (gift_card_id, invoice_id)
);

-- Invoice lines that are not tailoring orders. These cannot live in `orders`,
-- whose measurement_id and material_id are NOT NULL and meaningless for a
-- retail sale. branch_id records where a product line's stock came off, and is
-- NULL for a gift card, which has no stock.
CREATE TABLE invoice_items (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    invoice_id UUID NOT NULL REFERENCES invoices(id),
    kind TEXT NOT NULL CHECK (kind IN ('product', 'gift_card')),
    product_id UUID REFERENCES products(id),
    gift_card_id UUID REFERENCES gift_cards(id),
    branch_id UUID REFERENCES branch(id),
    description TEXT NOT NULL,
    quantity NUMERIC(10, 2) NOT NULL DEFAULT 1,
    unit_price NUMERIC(10, 2) NOT NULL,
    line_total NUMERIC(10, 2) NOT NULL,
    CHECK (
        (kind = 'product' AND product_id IS NOT NULL AND gift_card_id IS NULL)
        OR (kind = 'gift_card' AND gift_card_id IS NOT NULL AND product_id IS NULL)
    )
);


-- Staff-editable thob design catalog: the choices inside each fixed
-- order slot (thobe type, collar, sleeve, front pocket, side pocket, patti, EMD).
--
-- The slots themselves stay fixed columns on `orders` — only the options
-- live here, one row each, mirroring `order_stages` and its retirement
-- rule: `is_active` retires an option without disturbing the orders that
-- already stored its slug. `orders` keeps storing the bare slug as TEXT
-- (no foreign key), so a legacy value that matches nothing still prints
-- as a text-only chip rather than disappearing.
--
-- Images live beside the row as BYTEA so the printed invoice stays
-- self-contained (rendered to `data:` URIs, like the old compiled-in
-- catalog). SVG sits beside the rasters the same way — the documents carry
-- the stored mime into the data URI, so vectors replace illustrations option
-- by option with no pipeline change. Seeded NULL: until staff upload an illustration the
-- documents fall back to the compiled-in catalog for the matching
-- section+slug, so this seed changes no printed output on its own.
CREATE TABLE design_options (
    id UUID PRIMARY KEY DEFAULT uuidv7(),
    category TEXT NOT NULL CHECK (category IN
        ('thob_type', 'neck', 'sleeve', 'front_pocket', 'side_pocket', 'patti', 'emd')),
    slug TEXT NOT NULL,
    label TEXT NOT NULL,
    cost NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (cost >= 0),
    image BYTEA,
    image_mime TEXT NOT NULL DEFAULT 'image/webp',
    image_version BIGINT NOT NULL DEFAULT 1,
    sort_order INTEGER NOT NULL DEFAULT 1,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (category, slug)
);

